// Build: tokens.json -> CSS variables per theme, concatenate component CSS, bundle JS.
// Outputs: dist/{tokens.css, tokens.json, jaali.css, jaali.min.css, jaali.js, jaali.iife.js, jaali.d.ts}
// and copies the browser files into docs/assets for the docs site.
import { readFileSync, writeFileSync, mkdirSync, readdirSync, copyFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { build, transform } from 'esbuild';
import { resolveAll } from '../src/tokens/derive.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const p = (...a) => join(root, ...a);
const src = JSON.parse(readFileSync(p('src/tokens/themes.json'), 'utf8'));
const resolved = resolveAll(src);
mkdirSync(p('dist'), { recursive: true });

// ---------- tokens.css ----------
const kebab = (s) => s.replace(/[A-Z]/g, (c) => '-' + c.toLowerCase());
const decl = (tokens, mode) => {
  const lines = [];
  for (const [k, v] of Object.entries(tokens)) {
    if (k === 'groundImage') continue;
    lines.push(`--j-${kebab(k)}:${v}`);
  }
  lines.push(`--j-shadow-tile:${src.elevation[mode].tile}`);
  lines.push(`--j-shadow-raised:${src.elevation[mode].raised}`);
  lines.push(`--j-ground-image:${tokens.groundImage || 'linear-gradient(transparent,transparent)'}`);
  lines.push(`color-scheme:${mode}`);
  return lines.join(';\n  ');
};

const t = src.type;
const head = `:root{
  --j-font:${t.family};
  --j-ease:${src.motion.ease};
}`;

const themeBlocks = Object.entries(resolved).map(([name, m]) => {
  const isDefault = name === src.default;
  const th = `:root[data-theme="${name}"]`;
  // the default theme also answers when no data-theme is set
  const dark = isDefault ? `:root,${th}` : th;
  const sys = isDefault ? `:root:not([data-mode="dark"]),${th}:not([data-mode="dark"])` : `${th}:not([data-mode="dark"])`;
  const lightForced = isDefault ? `:root[data-mode="light"],${th}[data-mode="light"]` : `${th}[data-mode="light"]`;
  const darkForced = isDefault ? `:root[data-mode="dark"],${th}[data-mode="dark"]` : `${th}[data-mode="dark"]`;
  return [
    `/* ${name}: ${src.themes[name].label} */`,
    `${dark}{\n  ${decl(m.dark, 'dark')}\n}`,
    `@media (prefers-color-scheme: light){\n${sys}{\n  ${decl(m.light, 'light')}\n}\n}`,
    `${lightForced}{\n  ${decl(m.light, 'light')}\n}`,
    `${darkForced}{\n  ${decl(m.dark, 'dark')}\n}`
  ].join('\n');
});

const tokensCss = `/* jaali tokens. Generated by scripts/build.mjs from src/tokens/themes.json. Do not edit. */\n${head}\n\n${themeBlocks.join('\n\n')}\n`;
writeFileSync(p('dist/tokens.css'), tokensCss);

// ---------- tokens.json ----------
writeFileSync(p('dist/tokens.json'), JSON.stringify({
  default: src.default,
  themes: Object.fromEntries(Object.entries(resolved).map(([n, m]) => [n, { label: src.themes[n].label, ...m }])),
  elevation: src.elevation,
  motion: src.motion,
  type: src.type
}, null, 2) + '\n');

// ---------- jaali.css ----------
const cssFiles = readdirSync(p('src/css')).filter((f) => f.endsWith('.css')).sort();
const css = tokensCss + '\n' + cssFiles.map((f) => `/* ---- ${f} ---- */\n` + readFileSync(p('src/css', f), 'utf8')).join('\n');
writeFileSync(p('dist/jaali.css'), css);
writeFileSync(p('dist/jaali.min.css'), (await transform(css, { loader: 'css', minify: true })).code);

// ---------- JS ----------
// the theme list the browser needs (names, labels, swatches) is generated, never hand-copied
const themeMeta = Object.fromEntries(Object.entries(resolved).map(([n, m]) => [n, { label: src.themes[n].label, dark: m.dark, light: m.light }]));
writeFileSync(p('src/js/_themes.gen.js'), `// Generated by scripts/build.mjs. Do not edit.\nexport const THEMES = ${JSON.stringify(themeMeta, null, 2)};\nexport const DEFAULT_THEME = ${JSON.stringify(src.default)};\n`);

await build({ entryPoints: [p('src/js/index.js')], bundle: true, format: 'esm', outfile: p('dist/jaali.js'), target: 'es2020', legalComments: 'none' });
await build({ entryPoints: [p('src/js/index.js')], bundle: true, format: 'iife', globalName: 'Jaali', outfile: p('dist/jaali.iife.js'), target: 'es2020', minify: true, legalComments: 'none' });
if (existsSync(p('src/js/index.d.ts'))) copyFileSync(p('src/js/index.d.ts'), p('dist/jaali.d.ts'));

// ---------- fonts (optional, self-hosted Geist, SIL Open Font License) ----------
const fontSrc = p('node_modules/@fontsource-variable/geist');
mkdirSync(p('dist/fonts'), { recursive: true });
const FACES = [
  ['latin', 'U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD'],
  ['latin-ext', 'U+0100-02BA,U+02BD-02C5,U+02C7-02CC,U+02CE-02D7,U+02DD-02FF,U+0304,U+0308,U+0329,U+1D00-1DBF,U+1E00-1E9F,U+1EF2-1EFF,U+2020,U+20A0-20AB,U+20AD-20C0,U+2113,U+2C60-2C7F,U+A720-A7FF']
];
for (const [name] of FACES) copyFileSync(join(fontSrc, 'files', `geist-${name}-wght-normal.woff2`), p('dist/fonts', `geist-${name}-wght-normal.woff2`));
copyFileSync(join(fontSrc, 'LICENSE'), p('dist/fonts/OFL.txt'));
writeFileSync(p('dist/fonts.css'), `/* Geist variable, self-hosted. SIL Open Font License 1.1, see fonts/OFL.txt */\n` + FACES.map(([name, range]) =>
  `@font-face{font-family:'Geist';font-style:normal;font-display:swap;font-weight:100 900;src:url(./fonts/geist-${name}-wght-normal.woff2) format('woff2');unicode-range:${range}}`).join('\n') + '\n');

// ---------- docs ----------
mkdirSync(p('docs/assets'), { recursive: true });
copyFileSync(p('dist/jaali.css'), p('docs/assets/jaali.css'));
copyFileSync(p('dist/jaali.iife.js'), p('docs/assets/jaali.iife.js'));
copyFileSync(p('dist/fonts.css'), p('docs/assets/fonts.css'));
mkdirSync(p('docs/assets/fonts'), { recursive: true });
for (const f of readdirSync(p('dist/fonts'))) copyFileSync(p('dist/fonts', f), p('docs/assets/fonts', f));

console.log(`built ${Object.keys(resolved).length} themes, ${cssFiles.length} css files -> dist/`);
